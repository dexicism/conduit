const COLORS: Record<NodeDefinition["color"], string> = {
  indigo: "bg-indigo-500/15 text-indigo-600 dark:text-indigo-300",
  amber: "bg-amber-500/15 text-amber-600 dark:text-amber-300",
  emerald: "bg-emerald-500/15 text-emerald-600 dark:text-emerald-300",
  sky: "bg-sky-500/15 text-sky-600 dark:text-sky-300",
  rose: "bg-rose-500/15 text-rose-600 dark:text-rose-300",
  violet: "bg-violet-500/15 text-violet-600 dark:text-violet-300",
  slate: "bg-slate-500/15 text-slate-600 dark:text-slate-300",
};

export function NodeIcon({
  def,
  className,
  size = "md",
}: {
  def: NodeDefinition | undefined;
  className?: string;
  size?: "sm" | "md";
}) {
  const Icon = (def && ICONS[def.icon]) || CircleHelp;
  return (
    <span
      aria-hidden
      className={cn(
        "flex shrink-0 items-center justify-center rounded-lg",
        size === "md" ? "size-9" : "size-7",
        def ? COLORS[def.color] : "bg-muted text-muted-foreground",
        className,
      )}
    >
      <Icon className={size === "md" ? "size-[18px]" : "size-4"} />
    </span>
  );
}
